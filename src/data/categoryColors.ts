const DEFAULT_THEME: CategoryColorTheme = CATEGORY_THEMES.everyday;

/**
 * Resolves the theme for a category by ID or slug.
 */
export function getCategoryTheme(categoryId?: string): CategoryColorTheme & { accentText: string; borderHover: string } {
  if (!categoryId) {
    return {
      ...DEFAULT_THEME,
      accentText: DEFAULT_THEME.accentText || DEFAULT_THEME.iconColor,
      borderHover: DEFAULT_THEME.borderHover || DEFAULT_THEME.cardBorderHover,
    };
  }
  const lower = categoryId.toLowerCase();
  const theme = CATEGORY_THEMES[lower] || DEFAULT_THEME;
  return {
    ...theme,
    accentText: theme.accentText || theme.iconColor,
    borderHover: theme.borderHover || theme.cardBorderHover,
  };
}
